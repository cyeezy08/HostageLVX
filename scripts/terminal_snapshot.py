#!/usr/bin/env python3
"""Render a real offline CLI capture as a standalone terminal-style SVG.

Input must be a trusted, reviewed output file generated by the repo's CI
smoke command. This does not synthesize findings or run network probes.
"""
import argparse
import re
from pathlib import Path
from xml.sax.saxutils import escape

ANSI = re.compile(r"\x1b(?:\[[0-?]*[ -/]*[@-~]|\][^\x07]*(?:\x07|\x1b\\))")
MAX_LINES = 32
MAX_COLS = 102


def safe_lines(source: str) -> list[str]:
    source = ANSI.sub("", source)
    result = []
    for line in source.splitlines():
        clean = "".join(c if c.isprintable() and c not in "\r\t" else " " for c in line)
        result.append(clean[:MAX_COLS])
        if len(result) == MAX_LINES:
            break
    if not result:
        raise ValueError("refusing to render an empty capture")
    return result


def render(title: str, lines: list[str], accent: str) -> str:
    if accent not in {"#00FFC8", "#F6B44A", "#68BFFF"}:
        raise ValueError("invalid accent")
    line_h = 20
    width = 1040
    height = 96 + len(lines) * line_h + 34
    body = []
    for index, line in enumerate(lines):
        body.append(
            f'<text x="33" y="{110 + index * line_h}" '
            f'font-family="DejaVu Sans Mono,Consolas,monospace" '
            f'font-size="14" fill="#D8E5ED" xml:space="preserve">{escape(line)}</text>'
        )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}" role="img" aria-label="{escape(title)}">'
        f'<rect width="{width}" height="{height}" rx="12" fill="#080C12"/>'
        f'<rect x="1" y="1" width="{width-2}" height="{height-2}" rx="11" '
        f'fill="none" stroke="#26323D" stroke-width="2"/>'
        f'<rect y="0" width="{width}" height="62" rx="12" fill="#141C26"/>'
        f'<path d="M0 62H{width}" stroke="#26323D"/>'
        f'<circle cx="26" cy="31" r="6" fill="{accent}"/>'
        f'<text x="48" y="37" font-family="DejaVu Sans Mono,Consolas,monospace" '
        f'font-size="18" font-weight="700" fill="#FFFFFF">{escape(title)}</text>'
        f'<text x="{width-26}" y="37" text-anchor="end" '
        f'font-family="DejaVu Sans Mono,Consolas,monospace" font-size="12" '
        f'fill="#97A7B4">OFFLINE CLI CAPTURE / SOURCE OUTPUT</text>'
        + "".join(body) +
        f'<text x="33" y="{height-17}" font-family="DejaVu Sans Mono,Consolas,monospace" '
        f'font-size="11" fill="{accent}">LEVIATHAN X // REPRODUCIBLE TOOLING</text>'
        '</svg>\n'
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--title", required=True)
    parser.add_argument("--accent", required=True)
    opts = parser.parse_args()
    lines = safe_lines(opts.input.read_text(encoding="utf-8", errors="replace"))
    opts.output.parent.mkdir(parents=True, exist_ok=True)
    opts.output.write_text(render(opts.title, lines, opts.accent), encoding="utf-8")


if __name__ == "__main__":
    main()
